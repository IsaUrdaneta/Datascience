#Crear tres variables en Python

precio = 1200
cantidad = 3
descuento = 10

#Calcular el precio total sin descuento
total_sin_descuento = precio * cantidad

#Calcular el monto de descuento
monto_descuento = (precio * descuento) / 100

#Calcular el precio total con descuento
total_con_descuento = total_sin_descuento - monto_descuento

#Imprimir resultados
print(f"El precio del producto es: {precio}")
print(f"La cantidad comprada es: {cantidad}")
print(f"El descuento es: {descuento}%")
print(f"El total sin descuento es: {total_sin_descuento}")
print(f"El monto de descuento es: {monto_descuento}")
print(f"El total con descuento es: {total_con_descuento}")




